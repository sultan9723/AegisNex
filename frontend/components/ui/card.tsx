import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { glass?: boolean; gradient?: boolean; hover?: boolean }
>(({ className, glass, gradient, hover = true, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border shadow-md transition-all duration-300",
      glass
        ? "glass-card"
        : gradient
          ? "bg-surface-elevated/80 border-border/70 gradient-border"
          : "bg-surface-elevated/80 border-border/70",
      hover && "hover:border-border hover:shadow-lg hover:bg-surface-elevated/95",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

